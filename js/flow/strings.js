/** Look up a form string; {name} placeholders are filled from vars. */
export function ft(key, vars = {}) {
  const lang = getLang();
  let s = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

