const LS_KEY = "eclipse-lyrics-lang";

let lang = "en";

export function getLang() {
  return lang;
}

export function t(key) {
  return STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
}

export function detectLang() {
  try {
    const saved = localStorage.getItem(LS_KEY);
    if (saved === "fr" || saved === "en" || saved === "kab") return saved;
  } catch {
    /* ignore */
  }
  const nav = (navigator.language || "en").toLowerCase();
  if (nav.startsWith("fr")) return "fr";
  if (nav.startsWith("kab") || nav.startsWith("ber") || nav.includes("tqbaylit")) return "kab";
  return "en";
}

export function setLang(next) {
  lang = next === "fr" ? "fr" : next === "kab" ? "kab" : "en";
  try {
    localStorage.setItem(LS_KEY, lang);
  } catch {
    /* ignore */
  }
  document.documentElement.lang = lang === "kab" ? "kab" : lang;
  applyDom();
  return lang;
}

export function applyDom() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (!key) return;
    const val = t(key);
    if (el.tagName === "META") {
      el.setAttribute("content", val);
      return;
    }
    el.textContent = val;
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (key) el.setAttribute("placeholder", t(key));
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria");
    if (key) el.setAttribute("aria-label", t(key));
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    const key = el.getAttribute("data-i18n-title");
    if (key) el.setAttribute("title", t(key));
  });
  const meta = document.querySelector('meta[name="description"]');
  if (meta) meta.setAttribute("content", t("metaDescription"));
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.setAttribute("aria-pressed", btn.dataset.lang === lang ? "true" : "false");
  });
}

export function initI18n() {
  lang = detectLang();
  document.documentElement.lang = lang;
  applyDom();
}
